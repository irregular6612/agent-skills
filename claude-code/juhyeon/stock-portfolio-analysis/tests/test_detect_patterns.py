"""Golden-fixture regression tests for detect_patterns.py.

Fixtures are in tests/fixtures/patterns/ (generated by _generate.py — re-run
that script only when the algorithm's input schema changes).

Each test writes the resulting <ticker>-patterns.json into a tmp_path copy of
the fixture so the repo stays clean.
"""
from __future__ import annotations
import json
import shutil
import sys
from pathlib import Path

import pytest

SKILL_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(SKILL_DIR / "scripts"))

from detect_patterns import process  # noqa: E402

FIXTURE_DIR = Path(__file__).resolve().parent / "fixtures" / "patterns"


def _run(ticker: str, tmp_path: Path) -> dict:
    """Copy <ticker>-ohlcv.json into tmp_path, run process(), return parsed output."""
    src = FIXTURE_DIR / f"{ticker}-ohlcv.json"
    assert src.exists(), f"missing fixture: {src}"
    shutil.copy(src, tmp_path / src.name)
    result = process(ticker, tmp_path)
    assert result["status"] == "ok"
    out = json.loads((tmp_path / f"{ticker}-patterns.json").read_text())
    return out


def test_detects_clean_hs(tmp_path):
    out = _run("synthetic_hs", tmp_path)
    hs = [p for p in out["patterns"] if p["name"] == "head_and_shoulders"]
    assert len(hs) >= 1, f"expected ≥1 H&S, got {len(hs)}"
    assert any(p["confidence"] in ("medium", "high") for p in hs)
    top = next(p for p in hs if p["confidence"] in ("medium", "high"))
    assert top["target_price"] is not None
    assert len(top["pivots"]) == 5
    roles = [piv["role"] for piv in top["pivots"]]
    assert roles == ["left_shoulder", "left_neck", "head", "right_neck", "right_shoulder"]


def test_detects_double_top(tmp_path):
    out = _run("synthetic_double_top", tmp_path)
    dt = [p for p in out["patterns"] if p["name"] == "double_top"]
    assert any(p["confidence"] in ("medium", "high") for p in dt), \
        f"no medium/high DT in {[(p['confidence'], p['guards_failed']) for p in dt]}"
    top = next(p for p in dt if p["confidence"] in ("medium", "high"))
    assert top["target_price"] is not None
    assert top["neckline"]["start_price"] == top["neckline"]["end_price"]  # horizontal


def test_no_false_positive_on_random_walk(tmp_path):
    out = _run("synthetic_no_pattern", tmp_path)
    # A random walk MAY produce a few low-confidence emissions, but NONE should
    # be high. The contract is: high confidence requires neckline broken +
    # volume confirm + all 6 guards — a true random walk shouldn't hit that.
    high = [p for p in out["patterns"] if p["confidence"] == "high"]
    assert high == [], f"random walk produced high-confidence patterns: {high}"


def test_guards_reject_uneven_shoulders(tmp_path):
    """Right shoulder 11% higher than left (above shoulder_equality 5%) → no high-confidence H&S.

    Algorithm may still emit the candidate at low confidence because exactly one
    guard fails — that's per-spec (we surface the candidate so the agent can
    decide).  But it must NOT pass `shoulder_equality`.
    """
    out = _run("synthetic_uneven_shoulders", tmp_path)
    hs_high = [p for p in out["patterns"]
               if p["name"] == "head_and_shoulders" and p["confidence"] == "high"]
    assert hs_high == [], f"unevenshoulders produced high-conf H&S: {hs_high}"
    # If any H&S candidate exists, shoulder_equality must be in guards_failed
    hs_any = [p for p in out["patterns"] if p["name"] == "head_and_shoulders"]
    for p in hs_any:
        assert "shoulder_equality" in p["guards_failed"], \
            f"expected shoulder_equality guard to fail: {p['guards_failed']}"


def test_guards_reject_peaks_too_far(tmp_path):
    """Peaks 12% apart (P1=75, P2=85) → peak_equality guard must fail."""
    out = _run("synthetic_peaks_too_far", tmp_path)
    dt_high = [p for p in out["patterns"]
               if p["name"] == "double_top" and p["confidence"] == "high"]
    assert dt_high == [], f"peaks-too-far produced high-conf DT: {dt_high}"
    dt_any = [p for p in out["patterns"] if p["name"] == "double_top"]
    for p in dt_any:
        assert "peak_equality" in p["guards_failed"], \
            f"expected peak_equality to fail: {p['guards_failed']}"


def test_process_writes_required_top_level_keys(tmp_path):
    """Schema check — output must always have ticker, timeframe, as_of, patterns, params."""
    out = _run("synthetic_hs", tmp_path)
    for key in ("ticker", "timeframe", "as_of", "params", "patterns"):
        assert key in out, f"missing key {key} in output: {list(out.keys())}"
    assert out["timeframe"] == "daily"
    assert isinstance(out["patterns"], list)


def test_short_series_returns_empty_with_note(tmp_path):
    """Fewer than 30 bars should short-circuit with a 'note' field, not crash."""
    # Build a 10-bar tiny series
    src = FIXTURE_DIR / "synthetic_hs-ohlcv.json"
    payload = json.loads(src.read_text())
    payload["data"] = payload["data"][:10]
    payload["as_of"] = payload["data"][-1]["date"]
    (tmp_path / "TINY-ohlcv.json").write_text(json.dumps(payload, ensure_ascii=False))
    result = process("TINY", tmp_path)
    assert result["status"] == "ok"
    out = json.loads((tmp_path / "TINY-patterns.json").read_text())
    assert out["patterns"] == []
    assert out.get("note") == "insufficient_bars"

#!/usr/bin/env python3
"""structure_split.py — Monolithic LaTeX → 섹션별 폴더 구조 분리.

구 latex-project-manager/SKILL.md Command 1 (`structure`) 로직을 1:1로 Python화.

사용법:
    structure_split.py <tex_file> <output_dir> [--project-name NAME]

워크플로 (latex-project-manager SKILL.md Phase 1-4 그대로):
    Phase 1: 분석 — preamble 추출, \\section 경계 식별, bibliography 방식 확인
    Phase 2: 분리 — main.tex, content.tex, sections/NN_*.tex, refs.bib 생성
    Phase 3: 검증 — compile.sh 호출로 컴파일, 페이지 수 일치 확인
    Phase 4: Critique Loop — 외부 호출자가 처리 (이 스크립트는 1회 분리만)

원칙: 컨텐츠는 한 글자도 변경하지 않음 (구조 변경만). 단, 명백한 LaTeX 에러는 수정.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import List, Optional


# ---------------------------------------------------------------------------
# 데이터 모델
# ---------------------------------------------------------------------------

@dataclass
class TexSplit:
    """Monolithic .tex 파일을 분석한 결과."""
    preamble: str                       # \documentclass ~ \begin{document}
    frontmatter: str                    # \begin{document} ~ 첫 \section 전
    sections: List[tuple[str, str]] = field(default_factory=list)  # [(name, body), ...]
    bibliography: str = ""              # \bibliography{...} or inline thebibliography
    has_inline_bib: bool = False
    packages: List[str] = field(default_factory=list)


# ---------------------------------------------------------------------------
# Phase 1: 분석
# ---------------------------------------------------------------------------

SECTION_RE = re.compile(r'^\s*\\section\*?\s*\{([^}]+)\}', re.MULTILINE)
PACKAGE_RE = re.compile(r'\\usepackage(?:\[[^\]]*\])?\{([^}]+)\}')


def slugify_section(name: str) -> str:
    """\\section{Background \\& Motivation} → 'background'.

    규칙 (lpm_legacy/structure-rules.md):
    - 특수문자 제거 (&, :, etc.)
    - 공백 → 언더스코어
    - 소문자
    """
    s = name.replace(r'\&', '').replace('&', '')
    s = re.sub(r'[^\w\s]', '', s)  # 알파벳/숫자/언더스코어/공백 외 제거
    s = re.sub(r'\s+', '_', s.strip())
    return s.lower()


def split_tex(content: str) -> TexSplit:
    """Phase 1 — Monolithic .tex 파일을 구조 단위로 분리."""
    # 1. Preamble (\documentclass ~ \begin{document})
    m = re.search(r'(\\documentclass.*?)\\begin\{document\}', content, re.DOTALL)
    if not m:
        raise ValueError("\\documentclass ... \\begin{document} 패턴 미발견")
    preamble = m.group(1).rstrip() + '\n'
    body_start = m.end()

    # 2. Body: \begin{document} ~ \end{document}
    body_match = re.search(r'\\end\{document\}', content[body_start:])
    if not body_match:
        raise ValueError("\\end{document} 미발견")
    body = content[body_start:body_start + body_match.start()]

    # 3. Frontmatter: body 시작 ~ 첫 \section 전
    first_section = SECTION_RE.search(body)
    if first_section:
        frontmatter = body[:first_section.start()].strip() + '\n'
        sections_text = body[first_section.start():]
    else:
        frontmatter = body.strip() + '\n'
        sections_text = ""

    # 4. Sections 분리
    sections: List[tuple[str, str]] = []
    section_matches = list(SECTION_RE.finditer(sections_text))
    for i, sm in enumerate(section_matches):
        name = sm.group(1)
        start = sm.start()
        end = section_matches[i + 1].start() if i + 1 < len(section_matches) else len(sections_text)
        body_text = sections_text[start:end].rstrip() + '\n'
        sections.append((name, body_text))

    # 5. Bibliography 식별
    bib_inline = re.search(
        r'\\begin\{thebibliography\}.*?\\end\{thebibliography\}',
        sections_text, re.DOTALL,
    )
    bib_external = re.search(r'\\bibliography\s*\{([^}]+)\}', sections_text)

    bibliography = ""
    has_inline = False
    if bib_inline:
        bibliography = bib_inline.group(0)
        has_inline = True
        # bibliography를 마지막 섹션에서 분리
        if sections:
            last_name, last_body = sections[-1]
            sections[-1] = (last_name, last_body.replace(bibliography, '').rstrip() + '\n')
    elif bib_external:
        bibliography = bib_external.group(0)

    # 6. 패키지 목록
    packages = PACKAGE_RE.findall(preamble)

    return TexSplit(
        preamble=preamble,
        frontmatter=frontmatter,
        sections=sections,
        bibliography=bibliography,
        has_inline_bib=has_inline,
        packages=packages,
    )


# ---------------------------------------------------------------------------
# Phase 2: 분리 (파일 생성)
# ---------------------------------------------------------------------------

MAIN_TEX_TEMPLATE = r"""% main.tex — auto-generated by structure_split.py
\newcommand{{\professor}}{{{project}}}

{preamble_lines}

\graphicspath{{{{\professor/figures/}}}}

\tolerance=1000
\emergencystretch=3em
\hfuzz=2pt

\begin{{document}}
\input{{\professor/content}}
\end{{document}}
"""


def extract_documentclass(preamble: str) -> tuple[str, str]:
    """\\documentclass 라인과 나머지 preamble 분리."""
    m = re.match(r'(\\documentclass.*?\n)(.*)', preamble, re.DOTALL)
    if not m:
        return ("\\documentclass[11pt]{article}\n", preamble)
    return (m.group(1), m.group(2))


def convert_inline_bib_to_bibtex(inline: str) -> str:
    """\\begin{thebibliography}...\\end{thebibliography} → BibTeX entries.

    lpm_legacy/structure-rules.md 변환 규칙 따름.
    휴리스틱 entry type 추론:
        - "arXiv preprint" → @article
        - "Proceedings of" or "In \\textit{...}" → @inproceedings
        - "\\textit{Journal Name}" → @article
        - 기본: @misc
    """
    entries = []
    item_re = re.compile(
        r'\\bibitem(?:\[[^\]]*\])?\{([^}]+)\}(.+?)(?=\\bibitem|\\end\{thebibliography\})',
        re.DOTALL,
    )
    for m in item_re.finditer(inline):
        key = m.group(1).strip()
        body = m.group(2).strip()

        # entry type 추론
        if re.search(r'\\textit\s*\{[^}]*arXiv', body, re.IGNORECASE):
            entry_type = 'article'
            field_name = 'journal'
        elif re.search(r'Proceedings\s+of|In\s+\\textit\s*\{', body):
            entry_type = 'inproceedings'
            field_name = 'booktitle'
        elif re.search(r'\\textit\s*\{', body):
            entry_type = 'article'
            field_name = 'journal'
        else:
            entry_type = 'misc'
            field_name = 'note'

        # Year 추출
        year_m = re.search(r'\((\d{4})\)', body)
        year = year_m.group(1) if year_m else 'YYYY'

        # title 추출 시도 (저자 다음 마침표 후 첫 문장)
        # 간단 휴리스틱: body에서 첫 마침표 이후, \textit 이전
        clean_body = re.sub(r'\s+', ' ', body).strip()
        title_m = re.search(r'\(\d{4}\)\.\s*([^.]+)\.', clean_body)
        title = title_m.group(1).strip() if title_m else 'TITLE_PLACEHOLDER'

        # field value (italic 안의 텍스트)
        field_m = re.search(r'\\textit\s*\{([^}]+)\}', body)
        field_value = field_m.group(1).strip() if field_m else clean_body[:100]

        entries.append(
            f'@{entry_type}{{{key},\n'
            f'  author = {{AUTHOR_PLACEHOLDER}},\n'
            f'  title = {{{title}}},\n'
            f'  {field_name} = {{{field_value}}},\n'
            f'  year = {{{year}}},\n'
            f'}}'
        )

    return '\n\n'.join(entries) + '\n' if entries else ''


def write_split(split: TexSplit, output_dir: Path, project: str) -> None:
    """Phase 2 — 분리된 컴포넌트를 파일 시스템에 작성."""
    proj_dir = output_dir / project
    sections_dir = proj_dir / 'sections'
    figures_dir = proj_dir / 'figures'

    sections_dir.mkdir(parents=True, exist_ok=True)
    figures_dir.mkdir(parents=True, exist_ok=True)
    (figures_dir / '.gitkeep').touch()

    # main.tex (preamble 통합)
    docclass, preamble_rest = extract_documentclass(split.preamble)
    main_content = f"% main.tex — auto-generated by structure_split.py\n"
    main_content += f"\\newcommand{{\\professor}}{{{project}}}\n\n"
    main_content += docclass
    main_content += preamble_rest.rstrip() + "\n\n"
    main_content += r"\graphicspath{{\professor/figures/}}" + "\n\n"
    main_content += "\\tolerance=1000\n\\emergencystretch=3em\n\\hfuzz=2pt\n\n"
    main_content += "\\begin{document}\n"
    main_content += "\\input{\\professor/content}\n"
    main_content += "\\end{document}\n"
    (output_dir / 'main.tex').write_text(main_content, encoding='utf-8')

    # frontmatter
    (sections_dir / '00_frontmatter.tex').write_text(split.frontmatter, encoding='utf-8')

    # sections
    inputs = ['00_frontmatter']
    for i, (name, body) in enumerate(split.sections, start=1):
        slug = slugify_section(name)
        filename = f'{i:02d}_{slug}.tex'
        (sections_dir / filename).write_text(body, encoding='utf-8')
        inputs.append(filename.replace('.tex', ''))

    # bibliography
    if split.has_inline_bib:
        bibtex = convert_inline_bib_to_bibtex(split.bibliography)
        (proj_dir / 'refs.bib').write_text(bibtex, encoding='utf-8')
        bib_section = (
            "\\bibliographystyle{plainnat}\n"
            f"\\bibliography{{{project}/refs}}\n"
        )
        last_index = len(split.sections) + 1
        bib_filename = f'{last_index:02d}_bibliography.tex'
        (sections_dir / bib_filename).write_text(bib_section, encoding='utf-8')
        inputs.append(bib_filename.replace('.tex', ''))
    elif split.bibliography:
        # 이미 외부 .bib 참조 — bibliography 명령만 보존
        last_index = len(split.sections) + 1
        bib_filename = f'{last_index:02d}_bibliography.tex'
        (sections_dir / bib_filename).write_text(
            "\\bibliographystyle{plainnat}\n" + split.bibliography + "\n",
            encoding='utf-8',
        )
        inputs.append(bib_filename.replace('.tex', ''))

    # content.tex (\input orchestrator) — lpm_legacy 규칙: hardcoded 경로
    content_lines = [f"\\input{{{project}/sections/{name}}}" for name in inputs]
    (proj_dir / 'content.tex').write_text('\n'.join(content_lines) + '\n', encoding='utf-8')

    # .gitignore — templates/gitignore 복사 (있을 때만)
    skill_root = Path(__file__).resolve().parent.parent
    gitignore_template = skill_root / 'templates' / 'gitignore'
    if gitignore_template.is_file():
        shutil.copy(gitignore_template, output_dir / '.gitignore')


# ---------------------------------------------------------------------------
# Phase 3: 검증 (compile.sh 호출)
# ---------------------------------------------------------------------------

def verify_compile(output_dir: Path, verbose: bool = False) -> bool:
    """compile.sh 호출로 컴파일 검증. PDF 생성 시 True."""
    import subprocess
    compile_sh = Path(__file__).resolve().parent / 'compile.sh'
    main_tex = output_dir / 'main.tex'
    if not main_tex.is_file():
        print(f"ERROR: {main_tex} 없음", file=sys.stderr)
        return False
    cmd = ['bash', str(compile_sh), str(main_tex)]
    try:
        result = subprocess.run(cmd, capture_output=not verbose, text=True, timeout=300)
        if result.returncode != 0:
            print(f"ERROR: compile.sh 실패 (exit {result.returncode})", file=sys.stderr)
            if not verbose and result.stderr:
                print(result.stderr[-2000:], file=sys.stderr)
            return False
        return True
    except subprocess.TimeoutExpired:
        print("ERROR: 컴파일 5분 초과", file=sys.stderr)
        return False
    except FileNotFoundError:
        print(f"ERROR: bash 미설치 또는 {compile_sh} 없음", file=sys.stderr)
        return False


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main() -> int:
    parser = argparse.ArgumentParser(
        description="Monolithic .tex → 섹션별 폴더 구조로 분리"
    )
    parser.add_argument('tex_file', help="입력 .tex 파일")
    parser.add_argument('output_dir', help="출력 디렉토리")
    parser.add_argument(
        '--project-name', default=None,
        help="프로젝트 이름 (기본: 입력 파일명에서 추출)"
    )
    parser.add_argument(
        '--no-verify', action='store_true',
        help="Phase 3 컴파일 검증 skip"
    )
    parser.add_argument('-v', '--verbose', action='store_true')
    args = parser.parse_args()

    tex_path = Path(args.tex_file)
    if not tex_path.is_file():
        print(f"ERROR: 파일 없음: {tex_path}", file=sys.stderr)
        return 1

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    project = args.project_name or tex_path.stem
    if not re.match(r'^[a-zA-Z][a-zA-Z0-9_]*$', project):
        print(f"WARNING: project name '{project}' 가 비표준. snake_case 권장", file=sys.stderr)

    # Phase 1
    print(f"[structure_split] Phase 1 분석: {tex_path}")
    content = tex_path.read_text(encoding='utf-8')
    try:
        split = split_tex(content)
    except ValueError as e:
        print(f"ERROR: 분석 실패: {e}", file=sys.stderr)
        return 1

    print(f"  - 패키지 {len(split.packages)}개")
    print(f"  - 섹션 {len(split.sections)}개")
    print(f"  - bibliography: {'inline' if split.has_inline_bib else ('external' if split.bibliography else 'none')}")

    # Phase 2
    print(f"[structure_split] Phase 2 분리: {output_dir}/")
    write_split(split, output_dir, project)
    print(f"  - main.tex, {project}/content.tex, {project}/sections/00..NN_*.tex 생성")

    # Phase 3
    if not args.no_verify:
        print("[structure_split] Phase 3 컴파일 검증...")
        ok = verify_compile(output_dir, verbose=args.verbose)
        if not ok:
            print("WARNING: 컴파일 검증 실패. 출력 파일은 보존됨.", file=sys.stderr)
            return 2
        print("  ✓ 컴파일 성공")
    else:
        print("[structure_split] Phase 3 skip (--no-verify)")

    print(f"\n✓ 완료. 다음 단계: /latex:push {output_dir}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
